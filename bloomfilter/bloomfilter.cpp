// Pull the address field out of a line: "address", "address\tbalance",
// "address,balance", "address balance" or a quoted variant of any of those.
static bool extract_addr(const std::string &line, std::string &addr) {
    size_t tab = line.find('\t');
    size_t comma = line.find(',');
    size_t space = line.find(' ');

    if (tab != std::string::npos && (comma == std::string::npos || tab < comma)) {
        addr.assign(line, 0, tab);
    } else if (comma != std::string::npos && (space == std::string::npos || comma < space)) {
        addr.assign(line, 0, comma);
    } else if (space != std::string::npos) {
        addr.assign(line, 0, space);
    } else {
        addr = line;
    }

    while (!addr.empty() && (addr.back() == ' ' || addr.back() == '"'))
        addr.pop_back();
    while (!addr.empty() && (addr.front() == ' ' || addr.front() == '"'))
        addr.erase(addr.begin());

    return !addr.empty();
}

// True only for address types an ENABLED search can actually match, so that
// disabled types (and unmatchable ones such as bc1p) add no set bits to the
// filter and therefore do not raise its false-positive rate.
struct TypeWants {
    bool compressed;    // P2PKH(c) + P2WPKH
    bool uncompressed;  // P2PKH(u)
    bool p2sh;          // P2SH-P2WPKH
    bool p2pkh;         // any 1xxx hash160
};

static TypeWants wants_for(uint32_t type_mask) {
    TypeWants w;
    w.compressed   = (type_mask & 0x1u) != 0;
    w.uncompressed = (type_mask & 0x2u) != 0;
    w.p2sh         = (type_mask & 0x4u) != 0;
    w.p2pkh        = w.compressed || w.uncompressed;
    return w;
}

static bool address_type_relevant(const std::string &addr, const TypeWants &w) {
    char c0 = addr[0];
    if (c0 == '1') return w.p2pkh;
    if (c0 == '3') return w.p2sh;
    // bc1q P2WPKH: its witness program IS hash160(compressed pubkey), so the
    // compressed search matches it with no extra work.
    if ((c0 == 'b' || c0 == 'B') && addr.size() >= 4 &&
        (addr[1] == 'c' || addr[1] == 'C') && addr[2] == '1' &&
        (addr[3] == 'q' || addr[3] == 'Q')) return w.compressed;
    return false;   // bc1p (P2TR) and anything else: unmatchable
}

// Count how many addresses in the file would be inserted for `type_mask`,
// without touching a filter. The caller sizes the filter from this instead of
// from a fixed guess: guessing 200M for a file that holds ~30M allocates 4x the
// device memory and spreads the same bits across 4x the address space, which
// makes every probe walk a much larger and much colder array for no benefit.
// A line whose address fails to decode is counted here but not inserted later,
// which only makes the filter more conservative (fewer elements, lower FPR).
uint64_t count_addresses_in_file(const std::string &filepath, uint32_t type_mask) {
    std::ifstream fin(filepath);
    if (!fin) {
        fprintf(stderr, "  [!] Cannot open %s\n", filepath.c_str());
        return 0;
    }

    const TypeWants w = wants_for(type_mask);
    std::string line, addr;
    uint64_t n = 0;
    uint64_t line_no = 0;

    while (std::getline(fin, line)) {
        line_no++;
        if (line.empty() || line[0] == '#') continue;
        while (!line.empty() && (line.back() == '\r' || line.back() == '\n'))
            line.pop_back();
        if (!extract_addr(line, addr)) continue;
        if (address_type_relevant(addr, w)) n++;

        if (line_no % 5000000 == 0) {
            printf("\r  Counting: %llu lines, %llu addresses",
                   (unsigned long long)line_no, (unsigned long long)n);
            fflush(stdout);
        }
    }
    printf("\r  Counted %llu matchable addresses in %llu lines          \n",
           (unsigned long long)n, (unsigned long long)line_no);
    return n;
}

uint64_t load_addresses_to_bloom(const std::string &filepath, BloomFilter &bf,
                                 uint32_t type_mask) {
    std::ifstream fin(filepath);
    if (!fin) {
        fprintf(stderr, "  [!] Cannot open %s\n", filepath.c_str());
        return 0;
    }

    const TypeWants w = wants_for(type_mask);
    std::string line, addr;
    uint64_t loaded = 0;
    uint64_t skipped = 0;
    uint64_t line_no = 0;

    while (std::getline(fin, line)) {
        line_no++;

        // Skip empty lines and comments
        if (line.empty() || line[0] == '#') continue;

        // Trim CR/LF
        while (!line.empty() && (line.back() == '\r' || line.back() == '\n'))
            line.pop_back();

        if (!extract_addr(line, addr)) continue;

        if (!address_type_relevant(addr, w)) { skipped++; continue; }

        uint8_t h160[20];
        if (decode_address_to_h160(addr, h160)) {
            bf.insert(h160);
            loaded++;
        } else {
            skipped++;
        }

        if (line_no % 1000000 == 0) {
            printf("\r  Loading: %llu lines, %llu addresses, %llu skipped",
                   (unsigned long long)line_no, (unsigned long long)loaded,
                   (unsigned long long)skipped);
            fflush(stdout);
        }
    }

    printf("\r  Loaded %llu addresses from %llu lines (%llu skipped)          \n",
           (unsigned long long)loaded, (unsigned long long)line_no,
           (unsigned long long)skipped);

    return loaded;
}
